int	ft_atoi(const char *str)
{
	int	neg;
	int	nb;
	int	i;

	neg = 1;
	nb = 0;
	i = 0;
	while ((str[i] >= 9 && str[i] <= 13) || str[i] == 32)
		i++;
	while (str[i])
	{
		if (str[i] == '-')
			neg = -neg;
		else
		{
			nb = (10 * nb) + (str[i] - 48);
		}
		i++;
	}
	return (neg * nb);
}
